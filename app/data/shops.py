    """
    依地點類別和區域取得推薦店家，隨機回傳 N 家。
    """
    pool = []
    seen = set()

    # 優先：同區域的對應類別
    if area and area in AREA_CATEGORY_MAP:
        for key in AREA_CATEGORY_MAP[area]:
            for shop in SHOPS_BY_CATEGORY.get(key, []):
                if shop["name"] not in seen:
                    seen.add(shop["name"])
                    pool.append(shop)

    # 補充：依地點 category 的一般對應
    for key in CATEGORY_MAP.get(category, []):
        for shop in SHOPS_BY_CATEGORY.get(key, []):
            if shop["name"] not in seen:
                seen.add(shop["name"])
                pool.append(shop)

